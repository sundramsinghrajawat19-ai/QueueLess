
import { useState } from "react";

const services = [
  {
    id: 1,
    name: "Healthcare Clinic",
    description: "Medical consultations",
    icon: "🏥",
  },
  {
    id: 2,
    name: "College Office",
    description: "Student services",
    icon: "🎓",
  },
  {
    id: 3,
    name: "Bank Counter",
    description: "Banking services",
    icon: "🏦",
  },
  {
    id: 4,
    name: "Government Office",
    description: "Public services",
    icon: "🏛️",
  },
];

export default function JoinQueue({ onBack }) {
  const [name, setName] = useState("");
  const [location, setLocation] = useState("City Centre");
  const [serviceId, setServiceId] = useState(1);
  const [token, setToken] = useState(null);
  const [error, setError] = useState("");
  const [loading, setLoading] = useState(false);

  async function handleSubmit(event) {
    event.preventDefault();
    setError("");
    setLoading(true);

    try {
      const response = await fetch(
        "http://localhost:3000/api/tokens",
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({
            name: name.trim(),
            location,
            serviceId,
          }),
        }
      );

      const data = await response.json();

      if (!response.ok) {
        throw new Error(data.message || "Unable to generate token.");
      }

      setToken(data.token);
    } catch (err) {
      setError(
        err.message === "Failed to fetch"
          ? "Cannot connect to the server. Please ensure the backend is running."
          : err.message
      );
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="join-page">
      <nav className="join-navbar">
        <button className="back-button" onClick={onBack}>
          ← QueueLess
        </button>
        <span className="join-brand">QueueLess</span>
        <span className="join-step-label">
          {token ? "Your token" : "Join the queue"}
        </span>
      </nav>

      <main className="join-main">
        <section className="join-intro">
          <p className="join-eyebrow">SMART QUEUE MANAGEMENT</p>
          <h1>
            Your time matters.
            <br />
            <span>Skip the waiting.</span>
          </h1>
          <p>
            Choose your service, get your token, and know
            where you stand in the queue.
          </p>
        </section>

        {!token ? (
          <form className="join-form-card" onSubmit={handleSubmit}>
            <h2>Choose your service</h2>
            <p className="form-description">
              Where would you like to go today?
            </p>

            <div className="service-grid">
              {services.map((service) => (
                <button
                  key={service.id}
                  type="button"
                  className={`service-option ${
                    serviceId === service.id ? "selected" : ""
                  }`}
                  onClick={() => setServiceId(service.id)}
                >
                  <span className="service-icon">{service.icon}</span>
                  <span className="service-name">{service.name}</span>
                  <span className="service-detail">
                    {service.description}
                  </span>
                  <span className="service-radio">
                    {serviceId === service.id ? "✓" : ""}
                  </span>
                </button>
              ))}
            </div>

            <label htmlFor="queue-name">Your name</label>
            <input
              className="queue-input"
              id="queue-name"
              type="text"
              placeholder="Enter your full name"
              value={name}
              onChange={(event) => setName(event.target.value)}
              maxLength={80}
              required
            />

            <label htmlFor="queue-location">Choose location</label>
            <select
              className="queue-input"
              id="queue-location"
              value={location}
              onChange={(event) => setLocation(event.target.value)}
              required
            >
              <option value="City Centre">City Centre</option>
              <option value="University Road">University Road</option>
              <option value="Main Market">Main Market</option>
            </select>

            {error && <p className="form-error">{error}</p>}

            <button
              className="generate-token-button"
              type="submit"
              disabled={loading}
            >
              {loading ? "Generating your token..." : "Get my token →"}
            </button>

            <p className="form-note">
              Your token is generated by the QueueLess backend.
            </p>
          </form>
        ) : (
          <section className="token-result">
            <div className="result-ticket">
              <p className="join-eyebrow">YOUR QUEUE TOKEN</p>
              <h2>{token.tokenNumber}</h2>
              <p>{token.serviceName}</p>

              <div className="ticket-details">
                <p>
                  <strong>Name:</strong> {token.name}
                </p>
                <p>
                  <strong>Location:</strong> {token.location}
                </p>
                <p>
                  <strong>People ahead:</strong> {token.peopleAhead}
                </p>
                <p>
                  <strong>Estimated waiting time:</strong>{" "}
{token.estimatedWait === 0
  ? "You're next!"
  : `${token.estimatedWait} minutes`}
                </p>
                <p>
                  <strong>Status:</strong> {token.status}
                </p>
              </div>

              <p className="form-note">
                This is a development queue. Tokens are temporarily
                stored in server memory until MongoDB is connected.
              </p>

              <button
                className="generate-token-button"
                onClick={() => {
                  setToken(null);
                  setName("");
                  setError("");
                }}
              >
                Get another token
              </button>

              <button
                className="back-button"
                onClick={onBack}
                type="button"
              >
                Back to home
              </button>
            </div>
          </section>
        )}
      </main>
    </div>
  );
}
